import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
const context=await browser.newContext({permissions:['camera','microphone'],serviceWorkers:'block'});
const pages=await Promise.all([context.newPage(),context.newPage()]);
const exceptions=[];
for(const [i,p] of pages.entries())p.on('pageerror',e=>exceptions.push('tab '+i+': '+e.message));
for(const page of pages)await page.goto('http://127.0.0.1:4173/studio/',{waitUntil:'domcontentloaded'});
for(const page of pages)await page.locator('.chat-row[data-chat="anna"]').click();
await pages[0].locator('#call-audio').click();
await pages[0].locator('#studio-call-status').waitFor();
await pages[1].locator('#call-audio').click();
await pages[1].locator('#studio-call-status').waitFor();
await pages[0].waitForFunction(()=>document.querySelector('#studio-call-status')?.textContent?.includes('Active'),{timeout:30000}).catch(()=>{});
const states=await Promise.all(pages.map(p=>p.locator('#studio-call-status').textContent()));
console.log('WebRTC status',JSON.stringify(states));
assert.ok(states.some(t=>t?.includes('Active')),'WebRTC local peer must connect between tabs');
await pages[0].locator('#studio-call-hangup').click();
await pages[1].locator('#studio-call-hangup').click();
assert.ok(exceptions.length===0,exceptions.join('\n'));
await browser.close();
console.log('PASS: actual WebRTC connection between two browser tabs');
