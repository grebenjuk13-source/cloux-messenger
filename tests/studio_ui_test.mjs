import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser=await chromium.launch({headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
const context=await browser.newContext({viewport:{width:390,height:844},permissions:['camera','microphone'],acceptDownloads:true,serviceWorkers:'block'});
const page=await context.newPage();
const problems=[];
page.on('pageerror',e=>problems.push('Page error: '+e.message));
page.on('console',m=>{if(m.type()==='error'&&!/favicon|net::ERR_/i.test(m.text()))problems.push('Console: '+m.text())});
await page.goto('http://127.0.0.1:4173/studio/',{waitUntil:'domcontentloaded'});
await page.getByText('Інтерактивне демо').waitFor();
assert.ok(await page.locator('.chat-row').count()>=12,'Expected 12+ local demo chats');
await page.locator('.chat-row').first().click();
await page.getByText('Сьогодні · демонстрація').waitFor();
await page.locator('#draft').fill('Привіт Studio ❤️');
await page.locator('#send').click();
await page.getByText('Привіт Studio ❤️').waitFor();
await page.locator('#emoji-open').click();
await page.getByRole('dialog',{name:'Панель емодзі'}).waitFor();
await page.locator('#emoji-query').fill('серце');
assert.ok((await page.locator('#emoji-grid button').count())>0,'Emoji keyword search');
await page.locator('#close-emoji').click();
assert.equal(await page.locator('#emoji-keyboard').isVisible(),false);
await page.locator('#back-chat').click();
await page.locator('#search').fill('Помічник');
assert.equal(await page.locator('.chat-row').count(),1,'List filtering');
await page.locator('#search').fill('');
await page.locator('#preferences').click();
await page.getByRole('heading',{name:'Налаштування Cloux Studio'}).waitFor();
await page.locator('#sheet-close').click();
await page.screenshot({path:'cloux-studio-mobile.png'});
const desktop=await context.newPage();
await desktop.setViewportSize({width:1440,height:900});
desktop.on('pageerror',e=>problems.push('Desktop error: '+e.message));
await desktop.goto('http://127.0.0.1:4173/studio/',{waitUntil:'domcontentloaded'});
await desktop.locator('.chat-row').first().click();
assert.equal(await desktop.locator('.chat-view').isVisible(),true);
await desktop.screenshot({path:'cloux-studio-desktop.png'});
const download=await context.newPage();
download.on('pageerror',e=>problems.push('Download error: '+e.message));
await download.goto('http://127.0.0.1:4173/download.html',{waitUntil:'domcontentloaded'});
await download.locator('#nav-version').getByText('v6.1.0').waitFor();
assert.ok((await download.locator('#changelog-list li').count())>=4,'Changelog loads');
const [received]=await Promise.all([download.waitForEvent('download'),download.locator('#download-html').click()]);
assert.ok(received.suggestedFilename().endsWith('.html'),'Offline HTML export');
const path=await received.path();
assert.ok(path,'Downloaded file path');
await download.screenshot({path:'cloux-download-mobile.png'});
if(problems.length)throw new Error(problems.join('\n'));
console.log('PASS: Mobile + desktop Studio, messages, emoji search, settings, download and JS console');
await browser.close();
